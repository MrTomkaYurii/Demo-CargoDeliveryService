namespace DriversManagement.Domain.Drivers.Services.Http;

using DriversManagement.Domain.Drivers.Dtos;

/// <summary>
/// ====================================================================================
/// 🌐 ІНТЕРФЕЙС ТИПІЗОВАНОГО HTTP-КЛІЄНТА ДО DRIVERSBLOGMANAGEMENT
/// ------------------------------------------------------------------------------------
/// ПРИЗНАЧЕННЯ:
/// Абстракція для виконання синхронних HTTP REST-запитів до мікросервісу блогів водіїв
/// (DriversBlogManagement) в рамках патерну Gateway Aggregator / BFF.
///
/// ЧОМУ МИ СТВОРЮЄМО ОКРЕМИЙ КЛІЄНТ ДЛЯ КОЖНОГО МІКРОСЕРВІСУ?
/// 1. Принцип єдиної відповідальності (SRP):
///    Кожен клієнт відповідає виключно за комунікацію з одним конкретним мікросервісом.
/// 2. Ізольовані налаштування стійкості:
///    Для блогу (менш критичний функціонал) ми можемо налаштувати коротший таймаут
///    (наприклад, 2 секунди замість 10), щоб збій у блозі не затримував відповідь
///    всього Агрегатора.
/// 3. Типобезпечність:
///    Клієнт віддає чітко типізовані моделі DTO, приховуючи роботу з HTTP-статусами,
///    заголовками та десеріалізацією JSON.
/// ====================================================================================
/// </summary>
public interface IDriversBlogApiClient
{
    /// <summary>
    /// Отримує список останніх публікацій про вказаного водія з мікросервісу блогу.
    /// </summary>
    /// <param name="driverId">Унікальний ідентифікатор водія (Guid).</param>
    /// <param name="cancellationToken">Токен скасування для безпечного переривання запиту.</param>
    /// <returns>Список постів водія для зведеного дашборду.</returns>
    Task<List<AggregatedBlogPostDto>> GetDriverPostsAsync(Guid driverId, CancellationToken cancellationToken = default);
}
